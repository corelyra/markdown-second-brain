#!/usr/bin/env python3
"""Rebuild INDEX.md: one line per file in notes/, people/, projects/, from each file's
frontmatter description. Generated; never edit INDEX.md by hand.

Usage: python3 scripts/build-index.py [--dry-run]
  --dry-run   print the index instead of writing INDEX.md
Unknown options stop the script.
"""
import os, re, sys, glob, datetime

if '--help' in sys.argv or '-h' in sys.argv:
    print(__doc__)
    sys.exit(0)
_bad = [a for a in sys.argv[1:] if a != '--dry-run']
if _bad:
    sys.exit('build-index.py: unknown argument ' + ' '.join(_bad) + '\n' + __doc__)
DRY = '--dry-run' in sys.argv

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SECTIONS = [('projects', 'Projects'), ('people', 'People and organisations'), ('notes', 'Notes')]

def meta(path):
    t = open(path, encoding='utf-8').read()
    desc, upd, status = '', '', ''
    if t.startswith('---\n'):
        end = t.find('\n---\n', 4)
        fm = t[4:end] if end != -1 else ''
        m = re.search(r'^description:\s*"?(.*?)"?\s*$', fm, re.M)
        desc = m.group(1).replace('\\"', '"') if m else ''
        m = re.search(r'^updated:\s*(\S+)', fm, re.M)
        upd = m.group(1) if m else ''
    m = re.search(r'^Status:\s*\**([a-z]+)', t, re.M)
    status = m.group(1) if m else ''
    return desc, upd, status

out = ['# INDEX', '',
       'Generated by `scripts/build-index.py` from each file\'s frontmatter. Do not edit by hand.',
       'Scan this (or grep `^description:`) to find the right file, then open only that file.', '']
total = 0
for d, label in SECTIONS:
    files = sorted(glob.glob(os.path.join(ROOT, d, '*.md')))
    out += [f'## {label} ({len(files)})', '']
    for p in files:
        desc, upd, status = meta(p)
        name = os.path.relpath(p, ROOT)
        tag = f' [{status}]' if d == 'projects' and status else ''
        out.append(f'- `{name}`{tag} {desc} _({upd})_')
        total += 1
    out.append('')
# Write only when the entries changed, so INDEX.md does not show a diff every day.
idx = os.path.join(ROOT, 'INDEX.md')
old = open(idx, encoding='utf-8').read() if os.path.exists(idx) else ''
body = '\n'.join(out)
if DRY:
    print(body)
    print('(dry run: INDEX.md not written)')
elif old.split('## Sources')[0].strip() != body.strip():
    out += ['## Sources', f'- Built {datetime.date.today().isoformat()} from {total} files.']
    open(idx, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('INDEX.md:', total, 'entries (rewritten)')
else:
    os.utime(idx)  # mark the index as checked, so the watchdog sees it as current
    print('INDEX.md:', total, 'entries (unchanged)')
